say('θcj 是“在第 c 类里，第 j 个症状出现的概率”，比如膀胱炎的人里有多少比例尿急。后面这一串乘起来，就是 likelihood，似然。')
say('关键是这个连乘号。本来我们要的是“这六个症状一起出现”的概率，但是组合太多，数不过来。所以朴素贝叶斯做了一个假设：'
    '在同一类病人里面，六个症状互不相关。这样就能拆成六个单独的概率相乘，每个只要数一列就行，一共 6 乘 2，12 个数，72 条数据完全够用。'
    '这个假设叫条件独立，“朴素”就朴素在这儿。')
cue('在 ∏ 下面写“likelihood（条件独立）”')
say('还要注意一点：症状是 0 的时候不是不管它，而是乘 1 减 θ。“没有腰痛”本身也是信息，待会儿大家就能看到它起了多大作用。')
say('然后是平滑。')
cue('θ = (k+1)/(n+2)')
